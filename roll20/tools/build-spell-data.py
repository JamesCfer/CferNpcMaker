#!/usr/bin/env python3
"""Build the spell lists the Roll20 extension sends as `spellMapping`.

The Foundry modules read spell names and levels from Foundry compendiums; on
Roll20 there is no such index, so we ship one. Sources (clone them first):
  git clone --depth 1 --filter=blob:none --sparse https://github.com/foundryvtt/dnd5e.git
      && git sparse-checkout set --no-cone 'packs/_source/spells/**'
  git clone --depth 1 --filter=blob:none --sparse https://github.com/foundryvtt/pf2e.git
      && git sparse-checkout set --no-cone 'packs/pf2e/spells/**'

Usage: python3 build-spell-data.py <dnd5e-repo> <pf2e-repo>
D&D 5e spells are SRD 5.1 (CC-BY-4.0); PF2e spells are ORC/OGL content.
"""
import json, os, re, sys, html
import yaml

OUT = os.path.join(os.path.dirname(__file__), '..', 'core', 'data')
SCHOOLS = {'abj': 'Abjuration', 'con': 'Conjuration', 'div': 'Divination', 'enc': 'Enchantment',
           'evo': 'Evocation', 'ill': 'Illusion', 'nec': 'Necromancy', 'trs': 'Transmutation'}
ACT = {'action': '1 action', 'bonus': '1 bonus action', 'reaction': '1 reaction', 'minute': 'minute', 'hour': 'hour'}

def text(h):
    h = re.sub(r'<br\s*/?>|</p>\s*<p>', '\n', h or '')
    h = re.sub(r'@\w+\[[^\]]*\]\{([^}]*)\}', r'\1', h)
    h = re.sub(r'\[\[/\w+ ([^\]]*)\]\]', r'\1', h)
    h = re.sub(r'<[^>]+>', '', h)
    return html.unescape(h).replace('\u2014', ' - ').strip()

def dnd5e(root):
    out = []
    for dirpath, _, files in os.walk(os.path.join(root, 'packs/_source/spells')):
        for f in files:
            if not f.endswith('.yml') or f.startswith('_'): continue
            d = yaml.safe_load(open(os.path.join(dirpath, f)))
            if d.get('type') != 'spell': continue
            s = d['system']
            a = s.get('activation') or {}
            cast = ACT.get(a.get('type'), a.get('type') or '')
            if a.get('type') in ('minute', 'hour'): cast = f"{a.get('value') or 1} {a['type']}{'s' if str(a.get('value') or 1) != '1' else ''}"
            r = s.get('range') or {}
            rng = 'Self' if r.get('units') == 'self' else 'Touch' if r.get('units') == 'touch' else (f"{r.get('value')} {r.get('units')}".strip() if r.get('value') else (r.get('units') or ''))
            du = s.get('duration') or {}
            dur = 'Instantaneous' if du.get('units') == 'inst' else ('Until dispelled' if du.get('units') == 'perm' else f"{du.get('value') or ''} {du.get('units') or ''}".strip())
            props = s.get('properties') or []
            comps = ' '.join(c for c, p in (('V', 'vocal'), ('S', 'somatic'), ('M', 'material')) if p in props)
            out.append({'id': d['_id'], 'name': d['name'], 'level': s.get('level', 0), 'school': SCHOOLS.get(s.get('school'), ''),
                        'time': cast, 'range': rng, 'duration': dur, 'components': comps,
                        'material': (s.get('materials') or {}).get('value', ''),
                        'concentration': 'concentration' in props, 'ritual': 'ritual' in props,
                        'desc': text((s.get('description') or {}).get('value'))})
    out.sort(key=lambda x: (x['level'], x['name']))
    return out

def pf2e(root):
    out = []
    for dirpath, _, files in os.walk(os.path.join(root, 'packs/pf2e/spells')):
        for f in files:
            if not f.endswith('.json') or f.startswith('_'): continue
            d = json.load(open(os.path.join(dirpath, f)))
            if d.get('type') != 'spell': continue
            s = d['system']; t = s.get('traits') or {}
            out.append({'id': d['_id'], 'name': d['name'], 'level': (s.get('level') or {}).get('value', 1),
                        'cantrip': 'cantrip' in (t.get('value') or []), 'focus': 'focus' in (t.get('value') or []),
                        'traditions': t.get('traditions') or []})
    out.sort(key=lambda x: (x['level'], x['name']))
    return out

if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    for name, rows, note in (('dnd5e-spells', dnd5e(sys.argv[1]), 'D&D 5e SRD 5.1 spells, CC-BY-4.0, Wizards of the Coast. Built from foundryvtt/dnd5e.'),
                             ('pf2e-spells', pf2e(sys.argv[2]), 'Pathfinder 2e spells (ORC / OGL). Built from foundryvtt/pf2e. Names and levels only.')):
        with open(os.path.join(OUT, name + '.js'), 'w') as fh:
            fh.write(f'// Generated by roll20/tools/build-spell-data.py. Do not edit by hand.\n// {note}\n')
            fh.write('export default ' + json.dumps(rows, separators=(',', ':'), ensure_ascii=False) + ';\n')
        print(name, len(rows))
